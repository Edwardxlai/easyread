// Run against the isolated DPO preview paper with its PDF-derived figures.
module.exports = async function readerDock(page) {
  const assert = require('node:assert/strict');
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.locator('#paper .blk-figure img').first().waitFor({ state: 'attached' });
  await page.locator('[data-act=dock]').click();
  const groups = page.locator('.dock-group:visible');
  const pick = async (group, key) => {
    await group.locator('.dock-add').click();
    await group.locator('.dock-menu:popover-open [data-open="' + key + '"]').click();
  };
  await page.locator('#pageview .pv-scroll img').first().waitFor();
  await pick(groups.first(), 'notes');
  // A full-width dock must still leave its outer grip reachable to shrink it again.
  const dock = page.locator('#readerDock'), grip = page.locator('.panel-grip');
  const handle = await grip.boundingBox();
  await page.mouse.move(handle.x + handle.width / 2, handle.y + 100);
  await page.mouse.down(); await page.mouse.move(1, handle.y + 100, { steps: 12 }); await page.mouse.up();
  assert.ok((await dock.boundingBox()).x < 3, 'The dock can cover the entire reader');
  await groups.first().locator('.dock-add').click();
  await groups.first().locator('[data-split=columns]').click();
  const pdf = await page.locator('#pageview').boundingBox(), note = await page.locator('#notespanel').boundingBox();
  assert.ok(pdf.x < note.x && Math.abs(pdf.y - note.y) < 2, 'PDF and notes are side by side');
  await groups.last().locator('[data-key=notes]').dragTo(groups.first().locator('.dock-head'));
  await grip.dblclick();
  await page.locator('#notespanel [data-np=paper]').click();
  const original = await page.locator('#paperNote').inputValue();
  assert.equal(await page.locator('#pnMindmap').isVisible(), false, 'The sidebar note is writing-only');
  await page.locator('.dock-tab[data-key=notes]').dragTo(groups.first(), { targetPosition: { x: 120, y: 805 } });
  assert.equal(await groups.count(), 2, 'Dragging the notes tab to the bottom splits the dock');
  assert.equal(await page.locator('#pageview').isVisible(), true);
  assert.equal(await page.locator('#notespanel').isVisible(), true);
  const upper = groups.first(), lower = groups.last();
  assert.equal(await lower.locator('#notespanel').isVisible(), true);
  await lower.locator('.dock-tab[data-key=notes]').dragTo(upper.locator('.dock-head'));
  assert.equal(await groups.count(), 1);
  const area = await upper.locator('.dock-content').boundingBox();
  await upper.locator('.dock-tab[data-key=pages]').dragTo(upper.locator('.dock-content'), { targetPosition: { x: 90, y: Math.round(area.height * .28) } });
  assert.equal(await groups.count(), 2, 'Dropping on the top part of the editor puts the tab above it');
  assert.equal(await upper.locator('#pageview').isVisible(), true);
  assert.equal(await lower.locator('#notespanel').isVisible(), true);
  const initial = (await upper.boundingBox()).height;
  await page.locator('.dock-divider').focus(); await page.keyboard.press('ArrowDown');
  assert.ok((await upper.boundingBox()).height > initial);
  await page.locator('#pageview .pv-follow input').uncheck();
  await page.locator('[data-pv=next]').click();
  const pdfPage = await page.locator('.pv-label').textContent();
  const img = page.locator('#paper .blk-figure img').first();
  await img.click(); await page.locator('.figure-viewer').getByText('在侧栏打开').click();
  const imageTab = page.locator('.dock-tab[data-key^="fig:"]').first();
  await imageTab.waitFor();
  const resource = page.locator('.dock-resource:visible .media-image img').first();
  await resource.waitFor();
  await resource.evaluate(i => i.decode());
  assert.equal(await groups.count(), 2, 'Opening another resource keeps the pane limit');
  await page.mouse.move(400, 540); await page.mouse.wheel(0, 640);
  assert.equal(await resource.isVisible(), true);
  await pick(lower, 'map');
  assert.equal(await lower.locator('.dock-resource:visible').isVisible(), true);
  if (original.trim()) await lower.locator('.dock-map .markmap-node').first().waitFor();
  await pick(lower, 'notes');
  assert.equal(await page.locator('#paperNote').inputValue(), original);
  await pick(upper, 'pages');
  assert.equal(await page.locator('.pv-label').textContent(), pdfPage);
  await img.dragTo(upper.locator('.dock-head'));
  assert.equal(await upper.locator('.dock-tab[data-key^="fig:"][aria-pressed=true]').count(), 1);
  assert.equal(await groups.count(), 2);
  await pick(upper, 'pages');
  const before = await page.locator('#stage').boundingBox();
  await page.locator('[data-act=dock]').click();
  assert.equal(await page.locator('#readerDock').isVisible(), false);
  await page.locator('[data-act=dock]').click();
  assert.equal(await groups.count(), 2);
  assert.equal(await page.locator('#stage').evaluate(e => e.getBoundingClientRect().width), before.width);
  await pick(upper, 'gallery');
  const gallery = upper.locator('.dock-resource:visible');
  const expected = await page.evaluate(() => window.PR.media.blocks().map(b => b.id));
  assert.ok(expected.length > 1);
  assert.deepEqual(await gallery.locator('.dock-gallery-entry').evaluateAll(a => a.map(e => e.dataset.id)), expected);
  await gallery.locator('.dock-gallery-entry').last().scrollIntoViewIfNeeded();
  assert.ok(await gallery.evaluate(e => e.scrollTop > 0), 'All paper figures and tables share a vertical scroll');
  await upper.locator('[data-close=pages]').click();
  assert.equal(await upper.locator('[data-key=pages]').count(), 0);
  assert.equal(await gallery.isVisible(), true, 'Closing a background tab leaves the gallery active');
  assert.equal(await lower.locator('#notespanel').isVisible(), true);
  await gallery.evaluate(e => { e.scrollTop = 0; });
  if (process.env.DOCK_SCREENSHOT) {
    await page.evaluate(() => window.PR.applyTheme('dark'));
    await lower.locator('.dock-add').click();
    await page.locator('#readerDock').screenshot({path: process.env.DOCK_SCREENSHOT});
    await page.keyboard.press('Escape');
  }
  return { splitTopAndBottom: true, mergeByDrag: true, maxVisible: 2, closeBackgroundTab: true,
    galleryEntries: expected.length, noteMapHidden: true, mapTab: true, statePreserved: true };
};
