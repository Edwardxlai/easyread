"""“问 AI”的回答方式；和使用哪个模型分开选择。"""

from ..app.i18n import tr

DEFAULT = "standard"
STE100 = "ste100"
XRAY = "xray"
VALUES = (DEFAULT, STE100, XRAY)

# 回答方式只控制表达风格，不改变论文上下文的范围。
WHOLE_PAPER = VALUES


def parse(value=None) -> str:
    if value is None:
        return DEFAULT
    if value not in VALUES:
        raise ValueError(tr("回答方式只能是 standard / ste100 / xray"))
    return value


